// Hide while moving down; reveal when scrolling pauses or reverses.
const header = document.querySelector('.header');
let previousScrollY = Math.max(0, window.scrollY);
let headerIdleTimer;
function revealHeader() {
  header.classList.remove('is-hidden');
}
window.addEventListener('scroll', () => {
  const currentY = Math.max(0, window.scrollY);
  clearTimeout(headerIdleTimer);
  if (currentY > previousScrollY && currentY > header.offsetHeight && !header.contains(document.activeElement)) {
    header.classList.add('is-hidden');
  } else {
    revealHeader();
  }
  previousScrollY = currentY;
  headerIdleTimer = setTimeout(revealHeader, 220);
}, { passive: true });
header.addEventListener('focusin', revealHeader);

